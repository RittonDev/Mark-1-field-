def _is_capital(city: str | None, state: str | None) -> bool:
    if not city:
        return False
    plain = unicodedata.normalize("NFD", city)
    name = " ".join("".join(c for c in plain if unicodedata.category(c) != "Mn").lower().split())
    uf = (state or "").strip().upper()
    return (name, uf) in CAPITALS if uf else name in CAPITAL_NAMES


